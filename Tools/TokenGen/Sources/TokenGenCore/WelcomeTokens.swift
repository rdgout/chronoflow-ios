import Foundation

public func welcomeTokens(root: URL) throws -> Data {
    let board = try String(contentsOf: root.appending(path: "_design/canvas/Main.dc.html"), encoding: .utf8)
    let rules = [
        ("topPadding", #"padding: (\d+)px 24px 40px"#, "64"),
        ("gutter", #"padding: 64px (\d+)px 40px"#, "24"),
        ("bottomPadding", #"padding: 64px 24px (\d+)px"#, "40"),
        ("groupGap", #"column; gap: (16)px;"#, "16"),
        ("actionGap", #"column; gap: (12)px;"#, "12"),
        ("brandGap", #"align-items: center; gap: (\d+)px;"#, "8"),
        ("moonSize", #"aria-hidden="true" width="(\d+)""#, "28"),
        ("moonStroke", #"stroke-width="(\d+)""#, "2"),
        ("moonViewBox", #"viewBox="0 0 (\d+) 24""#, "24"),
        ("eyebrowMargin", #"margin: (\d+)px 0 0"#, "56"),
        ("cardVerticalPadding", #"padding: (\d+)px 20px"#, "16"),
        ("cardHorizontalPadding", #"padding: 16px (\d+)px"#, "20"),
        ("cardRadius", #"border-radius: (22)px"#, "22"),
        ("buttonHeight", #"height: (52)px"#, "52"),
        ("introRise", #"translateY\((\d+)px\)"#, "14"),
    ]
    var code = "// Generated by Tools/TokenGen from Main.dc.html. Do not edit.\nimport Foundation\n"
    code += "nonisolated public enum WelcomeTokens {\n"
    for (name, pattern, expected) in rules {
        let values = try captures(pattern, in: board)
        guard !values.isEmpty, values.allSatisfy({ $0 == expected }) else {
            throw GenerationError.invalid("Welcome board differs from plan: \(name)")
        }
        code += "public static var \(name): CGFloat { \(expected) }\n"
    }
    code += "}\n"
    return try formattedSwift(code, root: root)
}
