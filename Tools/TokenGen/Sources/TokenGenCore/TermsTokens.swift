import Foundation

func termsTokens(root: URL) throws -> Data {
    let board = try String(contentsOf: root.appending(path: "_design/canvas/TermsUpdate.dc.html"), encoding: .utf8)
    let patterns = [
        "brandSize": #"alt="" width="(\d+)""#,
        "summaryPadding": #"gap: 12px; padding: (\d+)px;"#,
        "bulletSize": #"width: (\d+)px; height: 6px;"#,
        "policyHeight": #"min-height: (\d+)px;"#,
        "titleSize": #"font-size: (\d+)px; line-height: 38px;"#,
        "titleLineHeight": #"font-size: 32px; line-height: (\d+)px;"#,
        "bodySize": #"gap: 12px; font-size: (\d+)px;"#,
        "bodyLineHeight": #"font-size: 15px; line-height: (\d+)px;"#,
    ]
    var code =
        "// Generated by Tools/TokenGen from TermsUpdate.dc.html. Do not edit.\nimport Foundation\nnonisolated public enum TermsTokens {\n"
    for key in patterns.keys.sorted() {
        let value = try captures(patterns[key]!, in: board)[0]
        code += "public static var \(key): CGFloat { \(value) }\n"
    }
    code += """
        }
        extension Typography {
            public static var termsTitle: Style {
                Style(face: .fraunces400Opsz32, size: Double(TermsTokens.titleSize), lineHeight: Double(TermsTokens.titleLineHeight),
                      tracking: screenPageTitle.tracking, relativeTo: .body)
            }
            public static var termsBody: Style {
                Style(face: .figtree400, size: Double(TermsTokens.bodySize), lineHeight: Double(TermsTokens.bodyLineHeight),
                      tracking: screenBody.tracking, relativeTo: .body)
            }
            public static var termsStrong: Style {
                Style(face: .figtree600, size: Double(TermsTokens.bodySize), lineHeight: Double(TermsTokens.bodyLineHeight),
                      tracking: screenLabel.tracking, relativeTo: .body)
            }
        }

        """
    return try formattedSwift(code, root: root)
}
