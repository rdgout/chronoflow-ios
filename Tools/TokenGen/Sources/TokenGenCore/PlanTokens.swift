import Foundation

public func planTokenOutputs(root: URL) throws -> [String: Data] {
    let source =
        try JSONSerialization.jsonObject(
            with: Data(contentsOf: root.appending(path: "Tools/TokenGen/plan-tokens.json"))) as! [String: Any]
    let design =
        try JSONSerialization.jsonObject(
            with: Data(contentsOf: root.appending(path: "_design/canvas/ds/chronoflow/tokens.json"))) as! [String: Any]
    let spacing = (design["spacing"] as! [String: Any])["tokens"] as! [[String: Any]]
    let points = Dictionary(
        uniqueKeysWithValues: spacing.compactMap { token -> (String, Double)? in
            guard let value = token["value"] as? String, value.hasSuffix("px"), let number = Double(value.dropLast(2))
            else { return nil }
            return (token["name"] as! String, number)
        })
    let base = points["space-1"]!
    var metrics = "// Generated by Tools/TokenGen. Do not edit.\npublic enum PlanMetrics {\n"
    for (name, multiplier) in (source["spacingMultipliers"] as! [String: Double]).sorted(by: { $0.key < $1.key }) {
        metrics += "public static var \(name): Double { \(number(base * multiplier)) }\n"
    }
    for (name, token) in (source["spacingTokens"] as! [String: String]).sorted(by: { $0.key < $1.key }) {
        guard let value = points[token] else { throw GenerationError.invalid("Missing spacing token \(token)") }
        metrics += "public static var \(name): Double { \(number(value)) }\n"
    }
    for (name, value) in (source["scalars"] as? [String: Double] ?? [:]).sorted(by: { $0.key < $1.key }) {
        metrics += "public static var \(name): Double { \(number(value)) }\n"
    }
    let laneType = (source["type"] as! [String: [String: Int]])["planLane"]!
    metrics += "public static var laneLabelSize: Double { \(laneType["size"]!) }\n"
    metrics += "public static var laneLabelLineHeight: Double { \(laneType["lineHeight"]!) }\n"
    for (name, values) in (source["type"] as! [String: [String: Int]]).sorted(by: { $0.key < $1.key }) {
        metrics += "public static var \(name)Size: Double { \(values["size"]!) }\n"
        metrics += "public static var \(name)LineHeight: Double { \(values["lineHeight"]!) }\n"
    }
    metrics += "public static var pointsPerMinute: Double { pointsPerHour / 60 }\n}\n"
    var type = "// Generated by Tools/TokenGen from planCompactNote. Do not edit.\nnonisolated enum PlanTypeMetrics {\n"
    for (name, values) in (source["type"] as! [String: [String: Int]]).sorted(by: { $0.key < $1.key }) {
        type +=
            "static var \(name): TypeMetrics { TypeMetrics(size: \(values["size"]!), lineHeight: \(values["lineHeight"]!), tracking: 0) }\n"
        type += "static var \(name)Face: FontFace { .figtree\(values["weight"]!) }\n"
    }
    type += "}\n"
    return [
        "Packages/ChronoFlowKit/Sources/PlanCore/PlanMetrics.generated.swift": try formattedSwift(metrics, root: root),
        "Packages/ChronoFlowKit/Sources/DesignSystem/PlanTypeMetrics.generated.swift": try formattedSwift(
            type, root: root),
    ]
}
