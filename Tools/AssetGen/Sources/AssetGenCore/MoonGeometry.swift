import CoreGraphics
import Foundation
import TokenGenCore

struct MoonGeometry {
    struct Arc {
        let center: CGPoint
        let radius: CGFloat
        let startAngle: CGFloat
        let endAngle: CGFloat
        let clockwise: Bool
    }

    let svgPath: String
    let viewBox: CGFloat
    let start: CGPoint
    let arcs: [Arc]

    init(board: String) throws {
        let svg = try captures(#"(<svg class="cfsp-move"[^>]*>.*?</svg>)"#, in: board)
        guard svg.count == 1,
            let box = try captures(#"viewBox="([^"]+)""#, in: svg[0]).first,
            let path = try captures(#"<path d="([^"]+)""#, in: svg[0]).first
        else { throw GenerationError.invalid("Missing board moon SVG") }
        let dimensions = box.split(separator: " ").compactMap { CGFloat(Double($0) ?? .nan) }
        guard dimensions.count == 4, dimensions[0] == 0, dimensions[1] == 0,
            dimensions[2] == 24, dimensions[3] == dimensions[2]
        else { throw GenerationError.invalid("Moon viewBox differs from plan") }
        try self.init(svgPath: path, viewBox: dimensions[2])
    }

    init(svgPath: String, viewBox: CGFloat = 24) throws {
        let pattern = #"([MaZ]|-?(?:\d+(?:\.\d*)?|\.\d+))"#
        let tokens = try captures(pattern, in: svgPath)
        let remainder = svgPath.replacingOccurrences(of: pattern, with: "", options: .regularExpression)
        guard remainder.allSatisfy({ $0.isWhitespace || $0 == "," }), tokens.count >= 12,
            tokens[0] == "M", tokens[3] == "a", tokens.last == "Z", (tokens.count - 5).isMultiple(of: 7),
            let x = Double(tokens[1]), let y = Double(tokens[2])
        else { throw GenerationError.invalid("Moon path must use M, relative circular arcs and Z") }
        self.svgPath = svgPath
        self.viewBox = viewBox
        start = CGPoint(x: x, y: y)
        var current = start
        var parsed: [Arc] = []
        for index in stride(from: 4, to: tokens.count - 1, by: 7) {
            let values = tokens[index..<index + 7].compactMap(Double.init)
            guard values.count == 7, values.allSatisfy(\.isFinite), values[0] > 0,
                values[0] == values[1], values[2] == 0, [0, 1].contains(values[3]), [0, 1].contains(values[4])
            else { throw GenerationError.invalid("Unsupported moon arc; expected an unrotated circle") }
            let end = CGPoint(x: current.x + values[5], y: current.y + values[6])
            let halfX = (current.x - end.x) / 2
            let halfY = (current.y - end.y) / 2
            let halfChord = hypot(halfX, halfY)
            guard halfChord > 0 else { throw GenerationError.invalid("Moon arc has coincident endpoints") }
            // SVG enlarges radii that cannot reach the endpoint before choosing the arc center.
            let radius = max(CGFloat(values[0]), halfChord)
            let factor =
                (values[3] == values[4] ? -1.0 : 1.0)
                * sqrt(max(0, radius * radius - halfChord * halfChord)) / halfChord
            let center = CGPoint(
                x: (current.x + end.x) / 2 + factor * halfY,
                y: (current.y + end.y) / 2 - factor * halfX)
            let from = atan2(current.y - center.y, current.x - center.x)
            var sweep = atan2(end.y - center.y, end.x - center.x) - from
            if values[4] == 1 && sweep < 0 { sweep += 2 * .pi }
            if values[4] == 0 && sweep > 0 { sweep -= 2 * .pi }
            parsed.append(
                Arc(center: center, radius: radius, startAngle: from, endAngle: from + sweep, clockwise: values[4] == 0)
            )
            current = end
        }
        arcs = parsed
    }

    var path: CGPath {
        let path = CGMutablePath()
        path.move(to: start)
        for arc in arcs {
            path.addArc(
                center: arc.center, radius: arc.radius, startAngle: arc.startAngle, endAngle: arc.endAngle,
                clockwise: arc.clockwise)
        }
        path.closeSubpath()
        return path
    }

    var swiftSource: String {
        var commands = ["path.move(to: CGPoint(x: \(number(start.x)), y: \(number(start.y))))"]
        for arc in arcs {
            commands.append(
                "path.addArc(center: CGPoint(x: \(number(arc.center.x)), y: \(number(arc.center.y))), radius: \(number(arc.radius)), startAngle: \(number(arc.startAngle)), endAngle: \(number(arc.endAngle)), clockwise: \(arc.clockwise))"
            )
        }
        commands.append("path.closeSubpath()")
        return """
            // Generated by Tools/AssetGen from the board's Lucide moon path. Do not edit.
            import CoreGraphics
            nonisolated enum MoonGlyph {
                static var viewBox: CGFloat { \(number(viewBox)) }
                static var path: CGPath {
                    let path = CGMutablePath()
                    \(commands.joined(separator: "\n"))
                    return path
                }
            }
            """
    }
}
