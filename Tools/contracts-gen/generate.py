#!/usr/bin/env python3
"""Translate the pinned web trip DTO dependency graph; reject unsupported TS syntax."""
import argparse
import difflib
from pathlib import Path
import re
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[2]
PIN = 'afd80dc0cd127e9ad864d8ac32699383826366c8'
PATHS = ['Data/Api', 'Data/Trips', 'Data/Plan', 'Planner/Output', 'Planner/Input', 'Enums', 'Planning/Copy']
RENAMES = {'ApiTripListItem': 'TripListItem', 'ApiTripDetail': 'TripDetail',
           'CheckStateView': 'CheckState', 'CheckMarkView': 'CheckMark', 'CheckKeyView': 'CheckKeyView',
           'TripCardProgress': 'TripProgress', 'GutterTickView': 'TickView'}
OVERRIDES = {
    ('BlockView', 'params'): ('FlightParamsView | LayoverParamsView | TransferParamsView | MovementBreakParamsView | ZoneChangeParamsView | SleepParamsView | NapParamsView | RestParamsView | AvoidLightParamsView | SeekLightParamsView | LightOkParamsView | LightNeutralParamsView | CaffeineServingParamsView | CaffeineOkParamsView | CaffeineRoutineParamsView | NoCaffeineParamsView | CaffeineServingDrinksParamsView | CaffeineOkDrinksParamsView | NoCaffeineDrinksParamsView | NoteBlockParamsView', 'BlockParams'),
    ('CopyArg', 'value'): ('string | number', 'CopyArgValue'),
    ('CopyLine', 'args'): ('(CopyArg| CaffeineCopyArg)[]', '[CopyArgument]'),
}
ROOT_TYPES = ['ApiTripListItem', 'ApiTripDetail', 'ApiTripInput', 'ApiTripReview',
              'ApiTripSaveResult', 'ApiTripInputSnapshot', 'ApiAirportSearchResults']
KEYWORDS = {'public', 'private', 'internal', 'return', 'case', 'default', 'extension', 'repeat', 'in', 'is', 'switch', 'where', 'throw', 'throws', 'try', 'false', 'true', 'none', 'operator'}

def identifier(value):
    words = re.split(r'[_-]', value)
    name = words[0] + ''.join(w[:1].upper() + w[1:] for w in words[1:])
    name = {'lightOk': 'lightOK', 'caffeineOk': 'caffeineOK'}.get(name, name)
    if name[:1].isdigit():
        name = 'value' + name
    return f'`{name}`' if name in KEYWORDS else name


def generate(repo):
    definitions = {}
    for path in PATHS:
        source = subprocess.check_output(['git', '-C', str(repo), 'show', f'{PIN}:resources/js/types/App/{path}/index.ts'], text=True)
        declarations = re.findall(r'export type (\w+) = (.*?);', source, re.S)
        for name, body in declarations:
            if name in definitions:
                raise ValueError(f'duplicate type: {name}')
            definitions[name] = body.strip()
    selected = set()

    def include(name):
        if name in selected:
            return
        selected.add(name)
        body = definitions[name]
        for ref in re.findall(r'\b[A-Z]\w*\b', re.sub(r"'[^']*'", '', body)):
            if ref != 'Record':
                include(ref)
    for name in ROOT_TYPES:
        include(name)
    # Check every planner/output and domain enum, including currently unused literals.
    for path in ['Planner/Output', 'Enums']:
        source = subprocess.check_output(['git', '-C', str(repo), 'show', f'{PIN}:resources/js/types/App/{path}/index.ts'], text=True)
        for name in re.findall(r'export type (\w+) =', source):
            include(name)

    def swift_type(ts):
        ts = ts.strip()
        record = re.fullmatch(r'Record<string, (.+)>', ts)
        if record:
            return '[String: ' + swift_type(record[1]) + ']'
        if ts == 'boolean | number | string | null':
            return 'JSONValue'
        if ts.endswith(' | null'):
            return swift_type(ts[:-7]) + '?'
        if ts.endswith('[]'):
            return '[' + swift_type(ts[:-2]) + ']'
        if ts in {'string': 'String', 'number': 'Int', 'boolean': 'Bool', 'object': 'JSONObject'}:
            return {'string': 'String', 'number': 'Int', 'boolean': 'Bool', 'object': 'JSONObject'}[ts]
        if ts in selected:
            return RENAMES.get(ts, ts)
        raise ValueError(f'unsupported field type: {ts}')

    output = [f'// Generated by Tools/contracts-gen from web {PIN}.\nimport Foundation\n']
    for name in sorted(selected):
        body, swift_name = definitions[name], RENAMES.get(name, name)
        if re.fullmatch(r"'[^']+'(?:\s*\|\s*'[^']+')*", body):
            literals = re.findall(r"'([^']+)'", body)
            cases = ['unknownValue' if v == 'unknown' else identifier(v) for v in literals]
            if len(set(cases)) != len(cases):
                raise ValueError(f'colliding enum cases: {name}')
            lines = [f'public enum {swift_name}: Codable, Sendable, Equatable, Hashable, RawRepresentable {{']
            lines += [f'    case {case}' for case in cases]
            lines += ['    case unknown(String)', '', '    public init(rawValue: String) {', '        switch rawValue {']
            lines += [f'        case "{v}": self = .{c}' for v, c in zip(literals, cases)]
            lines += ['        default: self = .unknown(rawValue)', '        }', '    }', '', '    public var rawValue: String {', '        switch self {']
            lines += [f'        case .{c}: "{v}"' for v, c in zip(literals, cases)]
            lines += ['        case .unknown(let raw): raw', '        }', '    }', '', '    public init(from decoder: any Decoder) throws {', '        self.init(rawValue: try decoder.singleValueContainer().decode(String.self))', '    }', '', '    public func encode(to encoder: any Encoder) throws {', '        var container = encoder.singleValueContainer()', '        try container.encode(rawValue)', '    }', '}']
        elif body == 'object':
            lines = [f'public typealias {swift_name} = JSONObject']
        elif body.startswith('{') and body.endswith('}'):
            fields = []
            for field in body[1:-1].strip().splitlines():
                match = re.fullmatch(r'readonly (\w+)(\?)?: (.+),', field.strip())
                if not match:
                    raise ValueError(f'unsupported declaration in {name}: {field}')
                key, optional, ts = match.groups()
                if (name, key) in OVERRIDES:
                    expected, kind = OVERRIDES[name, key]
                    if ts != expected:
                        raise ValueError(f'hand-written union changed: {name}.{key}')
                else:
                    kind = swift_type(ts)
                if name == 'ApiReviewPromptShape' and key in {'min', 'max'}:
                    if ts != 'number | null':
                        raise ValueError(f'prompt numeric bound changed: {key}')
                    kind = 'Double?'
                if optional and not kind.endswith('?'):
                    kind += '?'
                fields.append((key, kind))
            lines = [f'public struct {swift_name}: Codable, Sendable, Equatable {{']
            lines += [f'    public var {identifier(k)}: {t}' for k, t in fields]
            lines += ['', '    public init(', ',\n'.join(f'        {identifier(k)}: {t}' + (' = nil' if t.endswith('?') else '') for k, t in fields), '    ) {']
            lines += [f'        self.{identifier(k)} = {identifier(k)}' for k, _ in fields]
            lines += ['    }']
            if name == 'BlockView':
                lines += ['', '    public init(from decoder: any Decoder) throws {', '        let container = try decoder.container(keyedBy: CodingKeys.self)']
                for k, t in fields:
                    if k == 'params':
                        lines += ['        params = try BlockParams(type: type, from: container.superDecoder(forKey: .params))']
                    else:
                        method = 'decodeIfPresent' if t.endswith('?') else 'decode'
                        lines += [f'        {identifier(k)} = try container.{method}({t.rstrip("?")}.self, forKey: .{identifier(k)})']
                lines += ['    }']
            coding_keys = [(k, identifier(k)) for k, _ in fields if k != identifier(k).strip('`')]
            if coding_keys:
                lines += ['', '    enum CodingKeys: String, CodingKey {']
                lines += [f'        case {identifier(k)}' + (f' = "{k}"' if (k, identifier(k)) in coding_keys else '') for k, _ in fields]
                lines += ['    }']
            lines += ['}']
        else:
            raise ValueError(f'unsupported type: {name} = {body}')
        output.append('\n'.join(lines) + '\n')
    raw = '\n'.join(output)
    return subprocess.check_output(
        ['xcrun', 'swift', 'format', 'format', '--configuration', str(ROOT / '.swift-format'), '-'],
        input=raw, text=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--web-repo', type=Path, default=ROOT.parent / 'chronoflow-new')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = ROOT / 'Packages/ChronoFlowKit/Sources/AppCore/Contracts/Generated/TripPlan.swift'
    expected = generate(args.web_repo)
    if args.check:
        actual = target.read_text() if target.exists() else ''
        if actual != expected:
            sys.stderr.writelines(difflib.unified_diff(actual.splitlines(True), expected.splitlines(True), fromfile=str(target), tofile='regenerated'))
            return 1
        print(f'Contracts match web {PIN}; generated fields and enum literals verified.')
    else:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(expected)
    return 0

if __name__ == '__main__':
    sys.exit(main())
